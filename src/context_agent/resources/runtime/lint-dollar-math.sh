#!/usr/bin/env bash
# Compile an instrumented, disposable sibling of main.tex in the existing container.
# The original main.tex, main.pdf and context.log are never written by this script.
set -euo pipefail
if [[ $# -ne 3 ]]; then
  echo 'usage: lint-dollar-math.sh SOURCE.tex REPORT.json NONCE' >&2
  exit 2
fi
source_file="$(realpath "$1")"
report_file="$2"
nonce="$3"
runtime="$(cd "$(dirname "$0")" && pwd)"
source_dir="$(dirname "$source_file")"
driver="$source_dir/.context-agent-dollar-lint.tex"
log_file="$source_dir/.context-agent-dollar-lint.log"
rm -f "$report_file"
cleanup() {
  rm -f "$driver" "$log_file"
  for ext in pdf tuc log mpx mpr tmp synctex; do
    rm -f "$source_dir/.context-agent-dollar-lint.$ext"
  done
}
trap cleanup EXIT

# This is a textual *injection*, not syntax recognition: ConTeXt tokenizes all content.
python3 - "$source_file" "$driver" "$runtime/lint-dollar-setup.tex" <<'PY'
from pathlib import Path
import sys
source, driver, setup = map(Path, sys.argv[1:])
if not source.is_file():
    raise SystemExit(f"missing source: {source}")
# Use a sibling so relative includes resolve as in the original compilation.
# Adding a line shifts genuine source locations by exactly one line.
driver.write_bytes((f"\\input {setup.as_posix()}\n").encode('utf-8') + source.read_bytes())
PY
if [[ -n "${CONTEXT_AGENT_LINT_RUNNER:-}" ]]; then
  ( cd "$source_dir" && "$CONTEXT_AGENT_LINT_RUNNER" "$(basename "$driver")" > "$log_file" 2>&1 ) || {
    tail -n 50 "$log_file" >&2 || true
    exit 3
  }
else
  bash "$runtime/bootstrap-context.sh" --compile "$driver" "$log_file" || {
    tail -n 50 "$log_file" >&2 || true
    exit 3
  }
fi
[[ -s "${driver%.tex}.pdf" ]] || { echo 'lint compilation produced no PDF' >&2; exit 3; }

# Parse only explicit diagnostics generated by our TeX macro (no source heuristics).
python3 - "$log_file" "$report_file" "$nonce" <<'PY'
import json
import re
import sys
from pathlib import Path
log_path, report_path = map(Path, sys.argv[1:3])
nonce = sys.argv[3]
pattern = re.compile(r'CA-DOLLAR-LINT line (\d+)\b')
lines = set()
for line in log_path.read_text(encoding='utf-8', errors='replace').splitlines():
    match = pattern.search(line)
    if match:
        lines.add(max(1, int(match.group(1)) - 1))
findings = [{
    'rule_id': 'context-dollar-math',
    'file': 'main.tex',
    'line': number,
    'message': ('Im ConTeXt-Satzlauf wurde verbotene Dollar-Mathematik ausgeführt. '
                'Bei MetaPost kann die gemeldete Zeile auf das Ende des MP-Blocks zeigen.'),
    'repair_hint': ('Im normalen ConTeXt-Text $...$ durch \\m{...} ersetzen, '
                    '$$...$$ durch \\startformula ... \\stopformula. '
                    'In MetaPost-Beschriftungen stattdessen \\math{...} verwenden. '
                    'Mathematischen Inhalt unverändert lassen.'),
} for number in sorted(lines)]
report_path.parent.mkdir(parents=True, exist_ok=True)
report_json = json.dumps({'nonce': nonce, 'findings': findings}, ensure_ascii=False)
report_path.write_text(report_json, encoding='utf-8')
# Deliver the checker-produced report in the verified shell tool output.
# Container file indexing need not expose this dotfile.
print('CA-DOLLAR-LINT-REPORT-V1 ' + report_json, flush=True)
PY
